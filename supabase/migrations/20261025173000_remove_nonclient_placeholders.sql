-- Cleanup non-client placeholders from public.clients.
-- Keep associated leads/prospects; remove only client rows without any linked operational,
-- portal, contractual, or financial records. The predicate is idempotent.
DELETE FROM public.clients c
WHERE upper(trim(coalesce(c.nom_complet, c.nom, ''))) IN ('AGRICAPITAL', 'ZONGO BOUKARY')
  AND NOT EXISTS (SELECT 1 FROM public.plantations x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.paiements x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.transferts_paiements x WHERE x.client_source_id = c.id OR x.client_dest_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.remboursements x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.commissions x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.tickets_techniques x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.documents_acquisition x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.lots_hectares x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.acquisition_lots x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.leads x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.prospects x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.historique_actions x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.interventions_techniques x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.portail_messages x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.client_contracts x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.client_account_provision_outbox x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.rapports_visites_techniques x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.client_portal_sessions x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.client_cotitulaires_mandataires x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.beneficiaire_documents x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.plantation_activations x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.beneficiaire_attributions x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.client_portal_access_codes x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.portail_notifications x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.push_subscriptions x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.portail_support_requests x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.client_monnaie_mouvements x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.finance_transactions x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.finance_expenses x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.notification_client_preferences x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.acquisitions x WHERE x.client_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM public.workspace_tasks x WHERE x.linked_client_id = c.id);
