UPDATE public.acquisitions
SET formule_nom=CASE
  WHEN formule_code IN ('PALMINVEST_AUTONOME','TERRAPALM_AUTONOME') THEN 'Libre'
  WHEN formule_code IN ('PALMINVEST_DELEGUE','TERRAPALM_DELEGUE') THEN 'Sous gestion'
  WHEN formule_code='PALMTERROIR_FLEXIBLE_PLUS' THEN 'Flexible'
  WHEN formule_code='PALMTERROIR_ESSENTIELLE' THEN 'Essentielle'
  ELSE formule_nom
END,
updated_at=now()
WHERE formule_code IN ('PALMINVEST_AUTONOME','TERRAPALM_AUTONOME','PALMINVEST_DELEGUE','TERRAPALM_DELEGUE','PALMTERROIR_FLEXIBLE_PLUS','PALMTERROIR_ESSENTIELLE');

